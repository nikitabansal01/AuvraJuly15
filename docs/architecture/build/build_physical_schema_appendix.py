#!/usr/bin/env python3
"""Generate the physical-schema appendix from the current recovery migrations."""
from __future__ import annotations
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
MIGRATIONS = ROOT / "alembic" / "recovery_versions"
OUT = ROOT / "docs" / "architecture" / "09-physical-schema-appendix.md"

def tables(text: str) -> list[str]:
    python_tables = re.findall(r'op\.create_table\(\s*["\']([a-z_]+)["\']', text)
    sql_tables = re.findall(r'CREATE TABLE\s+((?:app|ops|runtime)\.[a-z_]+)', text, re.I)
    return python_tables + sql_tables

def main() -> None:
    revisions = []
    for path in sorted(MIGRATIONS.glob("*.py")):
        text = path.read_text(encoding="utf-8")
        revision = re.search(r'revision\s*(?::[^=]+)?=\s*["\']([^"\']+)', text)
        if not revision or revision.group(1) == "20260723_0001":
            continue
        found = tables(text)
        revisions.append((path.name, revision.group(1), found))
    lines = ["# Physical schema appendix - current migration inspection", "", "**Inspection date:** 2026-08-08  ", "**Status:** TARGET PARTIAL - disposable PostgreSQL 17.7 bootstrap and selected rollback/invariant paths are evidenced; final-head migration, contract and staging acceptance remain open.", "", "This appendix is generated by `build/build_physical_schema_appendix.py` from `alembic/recovery_versions/`. It describes declared DDL and limited disposable-database proof, not a successful deployment. The legacy baseline migration is excluded because it is restricted archive evidence.", "", "| Revision | Migration | Declared physical tables |", "|---|---|---:|"]
    all_tables = []
    for filename, revision, found in revisions:
        lines.append(f"| `{revision}` | `{filename}` | {len(found)} |")
        ops_tables = {"generation_jobs", "outbox_events", "idempotency_keys", "deletion_requests"}
        all_tables += [(revision, name if "." in name else f"{'ops' if name in ops_tables else 'app'}.{name}") for name in found]
    lines += ["", "## Declared target tables", "", "| Schema/table | Revision | Physical status | Notes |", "|---|---|---|---|"]
    for revision, name in all_tables:
        note = "`app.audit_events` corrects the former intended `ops` placement." if name == "app.audit_events" else "Migration DDL exercised in a disposable PG17 target; staging remains unverified."
        lines.append(f"| `{name}` | `{revision}` | TARGET_PARTIAL | {note} |")
    lines += ["", "## Planned but not declared here", "", "The vendor-managed `runtime.checkpoints`, `runtime.checkpoint_blobs`, `runtime.checkpoint_writes` and `runtime.checkpoint_migrations` remain TARGET PLANNED. Their retention/bootstrap evidence is not present. Contract operations, generated clients and staging acceptance are separately unverified even where DDL or local tests exist.", "", "## Missing evidence", "", "- Frozen final-head upgrade/downgrade proof after all v2 migrations stop changing.", "- Frozen OpenAPI operationIds and generated-client compatibility evidence.", "- Complete owner-scoped authorization and real-provider failure tests.", "- Restore/migration rehearsals reconciling exactly 1,022 legacy application rows and regenerated asset evidence."]
    OUT.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(OUT)

if __name__ == "__main__": main()
